#!/bin/bash
# NetworkManager dispatcher script: domain-based split tunnel for the Fairlyne VPN.
# Installed as /etc/NetworkManager/dispatcher.d/50-fairlyne-vpn by ./install (root-owned copy).
#
# How it works:
#   - NetworkManager's dnsmasq adds every IP it resolves for the domains in domains.txt
#     into the nftables sets dst4/dst6.
#   - Packets to those IPs get FWMARK; an ip rule sends marked packets to table ROUTE_TABLE.
#   - VPN up: ROUTE_TABLE holds "default dev tun0". VPN down: it is empty, so the lookup
#     falls through to the main table and the same domains go out directly over wifi.
#   - The VPN is IPv4 only: while it is up, IPv6 traffic to those domains is rejected so
#     clients fall back to IPv4 instead of bypassing the tunnel.
#   - DNS: the listed domains are routing domains of the VPN connection, so while it is up
#     dnsmasq asks the DNS servers the VPN pushes (if any); private ones go through the tunnel.

set -u

# VPN_UUID, VPN_SERVER_PORT: generated by ./install from connection.conf (not committed).
CONNECTION_FILE=/etc/NetworkManager/fairlyne-vpn.connection
NFT_TABLE="fairlyne_vpn"
FWMARK=0x1951
ROUTE_TABLE=1951

log() { logger -t fairlyne-vpn "$*"; }

# shellcheck source=/dev/null
source "$CONNECTION_FILE" || { log "$CONNECTION_FILE missing: run ./install"; exit 0; }

# Creates the table if missing. An existing one is kept (its sets and VPN rules are live
# state): ./install deletes it first so that edits to this definition take effect.
ensure_base() {
    if ! nft list table inet "$NFT_TABLE" >/dev/null 2>&1; then
        nft -f - <<EOF
table inet $NFT_TABLE {
    set dst4 { type ipv4_addr; }
    set dst6 { type ipv6_addr; }

    # Locally generated traffic: "type route" re-runs the routing decision after marking.
    chain mark_local {
        type route hook output priority mangle; policy accept;
        udp dport $VPN_SERVER_PORT return
        tcp dport $VPN_SERVER_PORT return
        ip daddr @dst4 meta mark set $FWMARK
        ip6 daddr @dst6 meta mark set $FWMARK
    }

    # Forwarded traffic (docker containers, VMs).
    chain mark_forwarded {
        type filter hook prerouting priority mangle; policy accept;
        ip daddr @dst4 meta mark set $FWMARK
        ip6 daddr @dst6 meta mark set $FWMARK
    }

    # The chains below are filled only while the VPN is up.
    # Sockets picked the wifi source address before being marked: rewrite it for the tunnel.
    chain nat {
        type nat hook postrouting priority srcnat; policy accept;
    }
    chain vpn_ipv6_local {
        type filter hook output priority filter; policy accept;
    }
    chain vpn_ipv6_forwarded {
        type filter hook forward priority filter; policy accept;
    }
}
EOF
        log "nftables table $NFT_TABLE created"
    fi
    if ! ip rule show | grep -q "fwmark $FWMARK lookup $ROUTE_TABLE"; then
        ip rule add fwmark "$FWMARK" lookup "$ROUTE_TABLE" priority "$ROUTE_TABLE"
    fi
}

flush_dnsmasq_cache() {
    # Cached answers do not feed the sets: start from fresh lookups.
    local pid_file=/run/NetworkManager/dnsmasq.pid
    [[ -f $pid_file ]] && kill -HUP "$(cat "$pid_file")" 2>/dev/null
}

flush_vpn_rules() {
    nft flush chain inet "$NFT_TABLE" nat
    nft flush chain inet "$NFT_TABLE" vpn_ipv6_local
    nft flush chain inet "$NFT_TABLE" vpn_ipv6_forwarded
}

vpn_up() {
    local iface=$1 ns
    nft flush set inet "$NFT_TABLE" dst4
    nft flush set inet "$NFT_TABLE" dst6
    # Only a private DNS server is internal to the VPN: a public one (e.g. 1.1.1.1) is reached
    # directly, or all other traffic to it would go through the tunnel too.
    for ns in ${VPN_IP4_NAMESERVERS:-}; do
        if [[ $ns =~ ^(10\.|192\.168\.|172\.(1[6-9]|2[0-9]|3[01])\.) ]]; then
            nft add element inet "$NFT_TABLE" dst4 "{ $ns }"
        fi
    done
    flush_dnsmasq_cache
    ip route replace default dev "$iface" table "$ROUTE_TABLE"
    sysctl -qw "net.ipv4.conf.$iface.rp_filter=2"  # replies arrive on tun0 for routes main does not know
    flush_vpn_rules
    nft add rule inet "$NFT_TABLE" nat meta mark "$FWMARK" oifname "$iface" masquerade
    nft add rule inet "$NFT_TABLE" vpn_ipv6_local meta mark "$FWMARK" meta nfproto ipv6 reject with icmpv6 admin-prohibited
    nft add rule inet "$NFT_TABLE" vpn_ipv6_forwarded meta mark "$FWMARK" meta nfproto ipv6 reject with icmpv6 admin-prohibited
    log "VPN up on $iface (VPN DNS: ${VPN_IP4_NAMESERVERS:-none}): listed domains now go through the tunnel"
}

vpn_down() {
    ip route flush table "$ROUTE_TABLE" 2>/dev/null
    flush_vpn_rules
    log "VPN down: listed domains now go out directly"
}

ensure_base

if [[ ${CONNECTION_UUID:-} == "$VPN_UUID" ]]; then
    case ${2:-} in
        vpn-up) vpn_up "${VPN_IP_IFACE:-$1}" ;;
        vpn-down) vpn_down ;;
    esac
fi
exit 0
